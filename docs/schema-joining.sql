-- Tables for the "Birikma" (joining) step: Qaida-style drills per letter.
-- Run once, before re-running docs/seed.sql. Same style as the other realdb tables.

-- One row per letter, like trace / writing / listen / repeat
create table realdb.joining
(
    id           bigint generated by default as identity primary key,
    letter_id    bigint       not null unique references realdb.letters (id) on delete cascade,
    instructions varchar(300) not null,
    is_active    integer default 1 constraint ch_joining_active check (is_active in (0, 1)),
    created_date date    default (now() at time zone 'Asia/Tashkent')
);

-- The drills of a letter, in order (simple → harder)
create table realdb.drill
(
    id           bigint generated by default as identity primary key,
    joining_id   bigint       not null references realdb.joining (id) on delete cascade,
    sort_order   int          not null,
    -- Fully vocalized Arabic, e.g. أَتَبَ
    text         varchar(30)  not null,
    -- What it practises, comma-separated, in this order: harakat,madd,sukun,shadda,tanwin,ghunna
    features     varchar(100) not null
        constraint ch_drill_features check (features ~ '^(harakat|madd|sukun|shadda|tanwin|ghunna)(,(harakat|madd|sukun|shadda|tanwin|ghunna))*$'),
    audio_url    varchar(500),
    is_active    integer default 1 constraint ch_drill_active check (is_active in (0, 1)),
    created_date date    default (now() at time zone 'Asia/Tashkent'),
    constraint uq_drill_order unique (joining_id, sort_order)
);
