/**
 * Generates `docs/seed.sql`: the default rows for the `realdb` schema of 63yil-api,
 * built from the same letter data the UI uses in mock mode (src/api/mock/lettersData.ts).
 *
 * Run:  npm run seed:sql
 *
 * The SQL is safe to run more than once: rows that already exist are skipped (ON CONFLICT DO NOTHING).
 * To change the content, edit lettersData.ts, run this again, and re-run the SQL on a fresh database.
 */
import { writeFileSync } from 'node:fs'
import { mockLetters } from '../src/api/mock/lettersData.ts'

/** SQL string literal: wraps in quotes and escapes quotes inside. */
const q = (value: string | null): string => (value === null ? 'null' : `'${value.replaceAll("'", "''")}'`)

const FORMS: [code: string, nameUz: string][] = [
  ['isolated', 'Alohida'],
  ['initial', 'Boshida'],
  ['medial', 'Oʻrtada'],
  ['final', 'Oxirida'],
]

const formId = (code: string) => `(select id from realdb.form where code = ${q(code)})`

const lines: string[] = []
const out = (line = '') => lines.push(line)

out('-- Default data for 63yil (Uzbek). Generated by `npm run seed:sql` in 63yil-ui; do not edit by hand.')
out('-- Safe to run more than once: existing rows are skipped.')
out()
out('begin;')
out()

out('-- Letter forms (which shape Trace/Write use)')
out('insert into realdb.form (code, name_uz) values')
out(FORMS.map(([code, name]) => `    (${q(code)}, ${q(name)})`).join(',\n'))
out('on conflict (code) do nothing;')
out()

out('-- The 28 letters')
out(
  'insert into realdb.letters (id, sort_order, arabic, arabic_name, name, sound, makhraj,\n' +
    '                            form_isolated, form_initial, form_medial, form_final,\n' +
    '                            example_arabic, example_translit, example_meaning) values',
)
out(
  mockLetters
    .map((l) =>
      [
        `    (${l.id}, ${l.order}, ${q(l.arabic)}, ${q(l.arabicName)}, ${q(l.name)}, ${q(l.sound)}, ${q(l.makhraj)},`,
        `     ${q(l.forms.isolated)}, ${q(l.forms.initial)}, ${q(l.forms.medial)}, ${q(l.forms.final)},`,
        `     ${q(l.example.arabic)}, ${q(l.example.transliteration)}, ${q(l.example.meaning)})`,
      ].join('\n'),
    )
    .join(',\n'),
)
out('on conflict (sort_order) do nothing;')
out()
out('-- Explicit ids were used above, so move the id counter past them.')
out("select setval(pg_get_serial_sequence('realdb.letters', 'id'), (select max(id) from realdb.letters));")
out()

out('-- Trace: draw over the dotted letter')
out('insert into realdb.trace (letter_id, form_id, instructions) values')
out(mockLetters.map((l) => `    (${l.id}, ${formId(l.activities.trace.form)}, ${q(l.activities.trace.instructions)})`).join(',\n'))
out('on conflict (letter_id) do nothing;')
out()

out('-- Write: draw from memory')
out('insert into realdb.writing (letter_id, form_id, instructions) values')
out(mockLetters.map((l) => `    (${l.id}, ${formId(l.activities.write.form)}, ${q(l.activities.write.instructions)})`).join(',\n'))
out('on conflict (letter_id) do nothing;')
out()

out('-- Listen: hear the letter, pick it among choices (audio_url null = browser voice until recordings exist)')
out('insert into realdb.listen (letter_id, audio_url, instructions) values')
out(mockLetters.map((l) => `    (${l.id}, ${q(l.activities.listen.audioUrl)}, ${q(l.activities.listen.instructions)})`).join(',\n'))
out('on conflict (letter_id) do nothing;')
out()

out('-- Listen quiz wrong answers: look-alike / sound-alike letters')
out('insert into realdb.listen_distractor (listen_id, distractor_letter_id)')
out('select li.id, v.distractor_letter_id')
out('from (values')
out(
  mockLetters
    .flatMap((l) => l.activities.listen.distractors.map((d) => `    (${l.id}, ${d.id})`))
    .join(',\n'),
)
out(') as v(letter_id, distractor_letter_id)')
out('join realdb.listen li on li.letter_id = v.letter_id')
out('on conflict do nothing;')
out()

out('-- Repeat: hear it, record yourself, compare')
out('insert into realdb.repeat (letter_id, audio_url, instructions) values')
out(mockLetters.map((l) => `    (${l.id}, ${q(l.activities.repeat.audioUrl)}, ${q(l.activities.repeat.instructions)})`).join(',\n'))
out('on conflict (letter_id) do nothing;')
out()

out('commit;')
out()

const target = new URL('../docs/seed.sql', import.meta.url)
writeFileSync(target, lines.join('\n'))
console.log(`Wrote ${target.pathname} (${mockLetters.length} letters)`)
